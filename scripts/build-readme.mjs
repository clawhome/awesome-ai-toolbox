const pick = (obj, lang) => (obj?.[lang] || "").trim();

function entryLine(tool, lang) {
  const name = pick(tool.name, lang) || pick(tool.name, "zh") || tool.slug;
  const desc = pick(tool.desc, lang) || pick(tool.desc, "zh");
  const detail = `${SITE}/ai/${tool.slug}`;
  let primary;
  let tail = "";
  if (LINK_MODE === "official" && tool.url) {
    primary = tool.url;
    tail = lang === "zh" ? ` · [详情](${detail})` : ` · [details](${detail})`;
  } else {
    primary = detail;
    if (tool.url) tail = lang === "zh" ? ` · [官网](${tool.url})` : ` · [website](${tool.url})`;
  }
  return `- **[${name}](${primary})** — ${desc}${tail}`;
}

function render(lang, tools, cats) {
  const L = LOCALES[lang];
  const visible = cats.filter((c) => tools.some((t) => t.category === c.id));
  const groups = ["create", "analyze", "industry"];
  const total = tools.length;
  const out = [];

  out.push(`[${L.otherLabel}](./${L.otherFile}) | **${L.selfLabel}**`);
  out.push("");
  out.push(`# ${L.h1}`);
  out.push("");
  out.push(`> ${L.tagline(total, visible.length)}`);
  out.push("");
  out.push(
    [
      "[![Awesome](https://awesome.re/badge.svg)](https://awesome.re)",
      `[![Stars](https://img.shields.io/github/stars/${REPO}?style=social)](https://github.com/${REPO}/stargazers)`,
      `[![Last commit](https://img.shields.io/github/last-commit/${REPO})](https://github.com/${REPO}/commits)`,
      `[![Tools](https://img.shields.io/badge/tools-${total}-blue)](#${slugify(L.toc)})`,
      "[![License: CC0-1.0](https://img.shields.io/badge/license-CC0--1.0-lightgrey)](./LICENSE)",
      `[![PRs Welcome](https://img.shields.io/badge/PRs-welcome-brightgreen)](./CONTRIBUTING.md)`,
    ].join("\n"),
  );
  out.push("");
  out.push("---");
  out.push("");

  // 目录
  out.push(`## ${L.toc}`);
  out.push("");
  for (const g of groups) {
    const inGroup = visible.filter((c) => c.group === g);
    if (!inGroup.length) continue;
    out.push(`**${L.groups[g]}**`);
    out.push("");
    for (const c of inGroup) {
      const n = tools.filter((t) => t.category === c.id).length;
      out.push(`- [${pick(c.name, lang)}](#${slugify(pick(c.name, lang))}) \`${n}\``);
    }
    out.push("");
  }
  out.push(`- [${L.popular}](#${slugify(L.popular)})`);
  out.push(`- [${L.about}](#${slugify(L.about)})`);
  out.push(`- [${L.data}](#${slugify(L.data)})`);
  out.push(`- [${L.contribute}](#${slugify(L.contribute)})`);
  out.push(`- [${L.license}](#${slugify(L.license)})`);
  out.push("");
  out.push("---");
  out.push("");

  // 分类正文
  for (const g of groups) {
    const inGroup = visible.filter((c) => c.group === g);
    if (!inGroup.length) continue;
    for (const c of inGroup) {
      const name = pick(c.name, lang);
      out.push(`## ${name}`);
      out.push("");
      out.push(`<sub>[${L.back}](#${slugify(L.toc)}) · \`${tools.filter((t) => t.category === c.id).length} ${L.countLabel}\`</sub>`);
      out.push("");
      for (const t of tools.filter((x) => x.category === c.id)) {
        out.push(entryLine(t, lang));
      }
      out.push("");
    }
  }

  out.push("---");
  out.push("");
  out.push(`## ${L.popular}`);
  out.push("");
  out.push(`<sub>${L.popularNote}</sub>`);
  out.push("");
  const popular = [...tools].filter((t) => t.visits > 0).sort((a, b) => b.visits - a.visits).slice(0, TOP_N);
  popular.forEach((t, i) => {
    const name = pick(t.name, lang) || t.slug;
    const cat = pick(cats.find((c) => c.id === t.category)?.name, lang);
    out.push(`${i + 1}. **[${name}](${SITE}/ai/${t.slug})** — ${cat}`);
  });
  out.push("");

  // 关于 / 数据 / 贡献 / 许可
  out.push(`## ${L.about}`);
  out.push("");
  out.push(...L.aboutText);
  out.push("");
  out.push(`## ${L.data}`);
  out.push("");
  out.push(`| ${L.dataTable[0][0]} | ${L.dataTable[0][1]} |`);
  out.push("| --- | --- |");
  for (const row of L.dataTable.slice(1)) out.push(`| ${row[0]} | ${row[1]} |`);
  out.push("");
  out.push(`## ${L.contribute}`);
  out.push("");
  out.push(...L.contributeText);
  out.push("");
  out.push(`## ${L.license}`);
  out.push("");
  out.push(L.licenseText);
  out.push("");
  out.push("---");
  out.push("");
  out.push(`<sub>${L.footer}</sub>`);
  out.push("");

  return out.join("\n");
}

function toCsv(tools, cats) {
  const esc = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;
  const head = ["slug", "name_zh", "name_en", "desc_zh", "desc_en", "category", "category_zh", "category_en", "url", "detail_url", "tags", "monthly_visits"];
  const lines = [head.join(",")];
  for (const t of tools) {
    const c = cats.find((x) => x.id === t.category);
    lines.push(
      [
        t.slug,
        pick(t.name, "zh"),
        pick(t.name, "en"),
        pick(t.desc, "zh"),
        pick(t.desc, "en"),
        t.category,
        pick(c?.name, "zh"),
        pick(c?.name, "en"),
        t.url,
        `${SITE}/ai/${t.slug}`,
        (t.tags || []).join(" / "),
        t.visits || "",
      ]
        .map(esc)
        .join(","),
    );
  }
  return lines.join("\n") + "\n";
}

const main = async () => {
  const [tools, cats] = await Promise.all([
    readFile(join(ROOT, "data/tools.json"), "utf8").then(JSON.parse),
    readFile(join(ROOT, "data/categories.json"), "utf8").then(JSON.parse),
  ]);

  const missingEn = tools.filter((t) => !pick(t.desc, "en")).length;

  for (const lang of ["zh", "en"]) {
    const md = render(lang, tools, cats);
    await writeFile(join(ROOT, LOCALES[lang].file), md);
    console.log(`✅ ${LOCALES[lang].file}  ${tools.length} 条  ${(md.length / 1024).toFixed(0)} KB`);
  }
  await writeFile(join(ROOT, "data/tools.csv"), toCsv(tools, cats));
  console.log(`✅ data/tools.csv`);

  if (missingEn) console.log(`\n⚠️ 有 ${missingEn} 条缺少英文描述，英文版会回退显示中文。`);
};

main().catch((err) => {
  console.error(`生成失败：${err.message}`);
  process.exit(1);
});
