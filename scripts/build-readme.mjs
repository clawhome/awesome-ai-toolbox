/**
 * 由 data/ 生成 README.md（中文，默认）与 README.en.md（英文），并导出 data/tools.csv。
 *
 * 环境变量：
 *   SITE      站点地址，默认 https://topxai.cn
 *   LINK_MODE 工具主链接指向哪里。
 *             "detail"   = 名称链接到站点详情页（默认，为站点引流）
 *             "official" = 名称链接到官方站点，详情页作为次要链接
 *
 * 用法：node scripts/build-readme.mjs
 */

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = (process.env.SITE || "https://topxai.cn").replace(/\/$/, "");
const LINK_MODE = process.env.LINK_MODE || "detail";
const TOP_N = 20;

const REPO = process.env.REPO || "clawhome/awesome-ai-toolbox";

/**
 * 复刻 GitHub 的标题锚点算法。
 * 注意：GitHub 是把「去掉标点后剩下的每个空格」逐个替换成 `-`，不做折叠，
 * 所以 "Text Generation & Editing" 的锚点是 `text-generation--editing`（双连字符）。
 */
const slugify = (text) =>
  text
    .toLowerCase()
    .trim()
    .replace(/[\u2000-\u206F\u2E00-\u2E7F\\'!"#$%&()*+,./:;<=>?@[\]^`{|}~]/g, "")
    .replace(/ /g, "-");

